"""Build the self-hosted MuziDisplay WOFF2 subset and its exact CSS range.

Requires ``fonttools`` and ``brotli`` in the active Python environment.
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
OUTPUT_FONT = ROOT / "public" / "fonts" / "pfan-hutu-subset.woff2"
OUTPUT_CSS = ROOT / "src" / "styles" / "font-face.css"
TEXT_FILE = Path(tempfile.gettempdir()) / "muzi-display-chars.txt"
SOURCE_EXTENSIONS = {".astro", ".tsx", ".ts", ".md", ".css", ".json"}
EXTRA_CHARACTERS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz，。！？：；、“”‘’（）《》【】—…·/+-→↗"


def collect_characters() -> str:
    characters = set(EXTRA_CHARACTERS)
    for path in (ROOT / "src").rglob("*"):
        if (
            not path.is_file()
            or path.suffix not in SOURCE_EXTENSIONS
            or "node_modules" in path.parts
            or "dist" in path.parts
        ):
            continue
        characters.update(path.read_text(encoding="utf-8", errors="ignore"))
    return "".join(sorted(characters))


def compact_unicode_range(codepoints: list[int]) -> str:
    runs: list[tuple[int, int]] = []
    start = previous = codepoints[0]
    for codepoint in codepoints[1:]:
        if codepoint == previous + 1:
            previous = codepoint
            continue
        runs.append((start, previous))
        start = previous = codepoint
    runs.append((start, previous))
    return ", ".join(
        f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"
        for start, end in runs
    )


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("Usage: subset-display-font.py <PFanHuTuTi-Regular.ttf>")

    source_font = Path(sys.argv[1]).resolve()
    if not source_font.is_file():
        raise FileNotFoundError(source_font)

    OUTPUT_FONT.parent.mkdir(parents=True, exist_ok=True)
    TEXT_FILE.parent.mkdir(parents=True, exist_ok=True)
    TEXT_FILE.write_text(collect_characters(), encoding="utf-8")

    subprocess.run(
        [
            sys.executable,
            "-m",
            "fontTools.subset",
            str(source_font),
            f"--output-file={OUTPUT_FONT}",
            "--flavor=woff2",
            f"--text-file={TEXT_FILE}",
            "--layout-features=*",
            "--name-IDs=*",
            "--name-legacy",
            "--name-languages=*",
            "--notdef-glyph",
            "--notdef-outline",
            "--recommended-glyphs",
            "--no-hinting",
        ],
        check=True,
    )

    font = TTFont(OUTPUT_FONT)
    unicode_range = compact_unicode_range(sorted(font.getBestCmap()))
    OUTPUT_CSS.write_text(
        "/* Generated by scripts/subset-display-font.py. */\n"
        "@font-face {\n"
        "  font-family: \"MuziDisplay\";\n"
        "  src: url('/fonts/pfan-hutu-subset.woff2') format('woff2'), "
        "local('PFanHuTuTi'), local('PF频凡胡涂体'), local('PFanHuTuTi-Regular');\n"
        "  font-display: swap;\n"
        "  font-style: normal;\n"
        "  font-weight: 400;\n"
        f"  unicode-range: {unicode_range};\n"
        "}\n",
        encoding="utf-8",
    )

    print(f"Wrote {OUTPUT_FONT} ({OUTPUT_FONT.stat().st_size} bytes)")
    print(f"Wrote {OUTPUT_CSS}")


if __name__ == "__main__":
    main()
